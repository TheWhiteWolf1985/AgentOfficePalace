"""Verify the original Blender delivery and copy only the two runtime assets/data."""
from pathlib import Path
import hashlib,json,shutil,sys
ROOT=Path(__file__).resolve().parents[1];SOURCE=ROOT/'Personaggi/Atrio'
inventory=json.loads((SOURCE/'checksums.json').read_text(encoding='utf8'))['files']
for name,sha in inventory.items():
    p=SOURCE/name
    assert p.resolve().is_relative_to(SOURCE.resolve()),name
    assert hashlib.sha256(p.read_bytes()).hexdigest()==sha,name
sys.path.insert(0,str(SOURCE/'resources'))
from inspect_character import inspect
contract=json.loads((SOURCE/'resources/constraints.json').read_text(encoding='utf8'))
placements=json.loads((SOURCE/'reception.placements.json').read_text(encoding='utf8'))
assert placements['count']==2 and placements['floor']=='@lobby' and placements['movement'] is False and placements['tasks'] is None and placements['agent_provider'] is None
assert placements['instance_scale']==1.15
assert placements['source_atrium_sha256']==hashlib.sha256((ROOT/'src/client/models/atrium.glb').read_bytes()).hexdigest()
rows=[]
for i,slot in enumerate(placements['placements']):
    name=['reception_a','reception_b'][i];assert slot['asset']==name+'.glb'
    assert slot['runtime_instance_scale']==[1.15]*3 and slot['runtime_position']==[(-1.1 if i==0 else 1.1),0,-10.8] and slot['runtime_rotY']==0
    raw=(SOURCE/slot['asset']).read_bytes();manifest=json.loads((SOURCE/(name+'.manifest.json')).read_text(encoding='utf8'))
    report=inspect(raw,contract,'human',manifest);assert report['status']=='PASS',report
    pos=slot['runtime_position'];scale=1.15;bounds=report['metrics'];lo=[round(pos[k]+bounds['bounds_min'][k]*scale,6) for k in range(3)];hi=[round(pos[k]+bounds['bounds_max'][k]*scale,6) for k in range(3)]
    rows.append({'id':slot['id'],'model':name,'sha256':manifest['sha256'],'position':dict(zip(['x','y','z'],pos)),'rotY':0,'scale':scale,'collider':{'id':slot['id'],'minX':lo[0],'maxX':hi[0],'minZ':lo[2],'maxZ':hi[2],'bottom':lo[1],'top':hi[1]}})
    shutil.copyfile(SOURCE/slot['asset'],ROOT/'src/client/models'/slot['asset'])
text='// Generated by scripts/import-reception-staff.py; GLBs are already Y-up, local scale 1.\nexport const RECEPTION_STAFF = '+json.dumps(rows,ensure_ascii=False,indent=2)+' as const;\n'
(ROOT/'src/shared/reception-staff.ts').write_text(text,encoding='utf8')
print('RECEPTION_STAFF_IMPORTED',len(rows),'original inventory verified:',len(inventory))
