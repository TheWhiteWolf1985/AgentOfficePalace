"""Verify the portable delivery and import application data without modifying the originals."""
from pathlib import Path
import hashlib
import itertools
import json
import math
import shutil
import struct

root = Path(__file__).resolve().parents[1]
source = root / 'sala_atrio'
package = json.loads((source / 'PACKAGE_MANIFEST.json').read_text(encoding='utf-8-sig'))
for row in package['files']:
    p = source / row['path']
    assert p.resolve().is_relative_to(source.resolve()), row['path']
    content = p.read_bytes()
    assert len(content) == row['bytes'] and hashlib.sha256(content).hexdigest() == row['sha256'], row['path']
asset = (source / 'delivery/atrium.glb').read_bytes()
sha = hashlib.sha256(asset).hexdigest()
assert sha == package['asset_glb_sha256']
magic, version, length = struct.unpack_from('<4sII', asset)
assert magic == b'glTF' and version == 2 and length == len(asset)
gltf = json.loads(asset[20:20 + struct.unpack_from('<I', asset, 12)[0]])
manifest = json.loads((source / 'delivery/atrium.manifest.json').read_text(encoding='utf-8-sig'))

def point(p):
    return dict(x=round(p[0], 5), y=round(p[2], 5), z=round(-p[1], 5))

def box(name, lo, hi):
    return dict(id=name, minX=round(lo[0], 5), maxX=round(hi[0], 5), minZ=round(lo[2], 5), maxZ=round(hi[2], 5), bottom=round(lo[1], 5), top=round(hi[1], 5))

colliders = {}
for c in manifest['colliders_reference_boxes']:
    lo, hi = c['min_blender_m'], c['max_blender_m']
    collider = box(c['node'], [lo[0], lo[2], -hi[1]], [hi[0], hi[2], -lo[1]])
    if c['node'].startswith('atrio_floor_'):
        collider['top'] = 0  # Finished floorboards, above the backing slab.
    colliders[c['node']] = collider

# The manifest's boxes are references, not a complete collision system. Add the actual
# architecture, reception and original furnishings using transformed GLB mesh bounds.
nodes = gltf['nodes']
parents = {child: i for i, node in enumerate(nodes) for child in node.get('children', [])}
def transform(p, node):
    if 'matrix' in node:
        m = node['matrix']
        return [sum(m[k * 4 + i] * (p[k] if k < 3 else 1) for k in range(4)) for i in range(3)]
    p = [v * s for v, s in zip(p, node.get('scale', [1, 1, 1]))]
    x, y, z, w = node.get('rotation', [0, 0, 0, 1])
    a, b, c = p
    tx, ty, tz = 2 * (y*c-z*b), 2 * (z*a-x*c), 2 * (x*b-y*a)
    rotated = [a+w*tx+y*tz-z*ty, b+w*ty+z*tx-x*tz, c+w*tz+x*ty-y*tx]
    return [v+t for v,t in zip(rotated, node.get('translation', [0, 0, 0]))]

prefixes = ('atrio_wall_', 'atrio_window_', 'atrio_entrance_post_', 'atrio_ceiling_slab_',
            'atrio_reception_body', 'atrio_reception_top', 'atrio_reception_worktop',
            'atrio_bench_', 'atrio_stair_rail', 'atrio_stair_post')
for i, node in enumerate(nodes):
    name = node.get('name', '')
    original_pot = name.startswith('atrio_plant_') and name.endswith('_pot')
    if 'mesh' not in node or name in colliders or not (name.startswith(prefixes) or original_pot):
        continue
    points = []
    for primitive in gltf['meshes'][node['mesh']]['primitives']:
        a = gltf['accessors'][primitive['attributes']['POSITION']]
        for corner in itertools.product(*zip(a['min'], a['max'])):
            p, at = list(corner), i
            while True:
                p = transform(p, nodes[at])
                if at not in parents:
                    break
                at = parents[at]
            points.append(p)
    colliders[name] = box(name, [min(p[k] for p in points) for k in range(3)], [max(p[k] for p in points) for k in range(3)])

seats = []
for s in manifest['enrichment']['waiting_seats']:
    dx = s['stand_blender_m'][0] - s['position_blender_m'][0]
    dy = s['stand_blender_m'][1] - s['position_blender_m'][1]
    distance = math.hypot(dx, dy)
    assert distance > 0
    seats.append(dict(id=s['seat'], stand=point(s['stand_blender_m']), position=point(s['position_blender_m']),
                      facing=point([dx / distance, dy / distance, 0])))
data = dict(sourceSha256=sha, height=manifest['internal_height_m'], logo=manifest['enrichment']['logo'],
            seats=seats, colliders=list(colliders.values()))
lines = ['// Generated by scripts/import-atrium.py; GLB is already application Y-up.', 'export const ATRIUM_DATA = {']
for key, value in data.items():
    if isinstance(value, list):
        lines += ['  '+key+': ['] + ['    '+json.dumps(v, ensure_ascii=False, separators=(',', ':'))+',' for v in value] + ['  ],']
    else:
        lines += ['  '+key+': '+json.dumps(value, ensure_ascii=False, separators=(',', ':'))+',']
lines += ['} as const;', '']
(root / 'src/shared/atrium-data.ts').write_text('\n'.join(lines), encoding='utf8', newline='\n')
shutil.copyfile(source / 'delivery/atrium.glb', root / 'src/client/models/atrium.glb')
print('Verified', len(package['files']), 'package entries; GLB', sha, '; seats', len(seats), '; colliders', len(colliders))
